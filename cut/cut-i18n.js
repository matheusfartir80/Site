  function interpolar(texto, vars) {
    return String(texto).replace(/\{(\w+)\}/g, function (_, k) {
      return k in vars ? vars[k] : "";
    });
  }

  function renderTituloComDestaques(el, markedText) {
    if (!el || !markedText) return;
    el.innerHTML = "";
    var text = String(markedText);
    var rx = /\[([^\]]+)\]/g;
    var lastIdx = 0;
    var match;
    while ((match = rx.exec(text)) !== null) {
      if (match.index > lastIdx) {
        el.appendChild(document.createTextNode(text.slice(lastIdx, match.index)));
      }
      var span = document.createElement("span");
      span.className = "hl";
      span.textContent = match[1];
      el.appendChild(span);
      lastIdx = rx.lastIndex;
    }
    if (lastIdx < text.length) {
      el.appendChild(document.createTextNode(text.slice(lastIdx)));
    }
  }

  function urlHttps(value) {
    if (!value || !String(value).trim()) return "";
    try {
      var url = new URL(String(value).trim());
      return url.protocol === "https:" && !url.username && !url.password ? url.href : "";
    } catch (e) { return ""; }
  }

  function urlPlay(value) {
    var safe = urlHttps(value);
    if (!safe) return "";
    var url = new URL(safe);
    return url.hostname === "play.google.com" && url.pathname === "/store/apps/details" && url.searchParams.get("id") ? safe : "";
  }

  function urlInteresse(dict) {
    var phone = String(c.WHATSAPP_SUPORTE || "").replace(/\D/g, "");
    if (phone.length === 10 || phone.length === 11) phone = "55" + phone;
    if (!/^\d{12,15}$/.test(phone)) return "";
    return "https://wa.me/" + phone + "?text=" + encodeURIComponent(dict.interest_message);
  }

  function atualizarVideo() {
    var section = document.querySelector('[data-role="demo-section"]');
    var video = document.querySelector('[data-role="demo-video"]');
    if (!section || !video) return;
    var raw = String(c.VIDEO_DEMONSTRACAO_URL || "").trim();
    var source = "";
    if (raw) {
      try {
        var url = new URL(raw, window.location.href);
        var local = url.origin === window.location.origin && /^(https?:|file:)$/.test(url.protocol);
        if (!url.username && !url.password && (local || url.protocol === "https:")) source = url.href;
      } catch (e) {}
    }
    section.hidden = !source;
    if (source) {
      var webmSrc = /\.mp4($|\?)/i.test(source) ? source.replace(/\.mp4($|\?)/i, ".webm$1") : "";
      if (webmSrc && !video.querySelector('source[type="video/webm"]')) {
        video.removeAttribute("src");
        video.innerHTML = "";
        var sWebm = document.createElement("source");
        sWebm.src = webmSrc;
        sWebm.type = "video/webm";
        var sMp4 = document.createElement("source");
        sMp4.src = source;
        sMp4.type = "video/mp4";
        video.appendChild(sWebm);
        video.appendChild(sMp4);
        video.load();
      } else if (!webmSrc && video.getAttribute("src") !== source) {
        video.setAttribute("src", source);
      }
    }
    if (!source) {
      video.removeAttribute("src");
      video.innerHTML = "";
    }
    // A missing/unsupported media file must not leave a broken player on the page.
    video.onerror = function () { section.hidden = true; };
  }

